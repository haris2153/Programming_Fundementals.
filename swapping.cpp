// swapping values:
#include <iostream>
using namespace std;
int main()
{
	int a , b , c , temp;
	a = 2;
	b = 3;
	c = 4;
	
	temp = a;
	 a = c;
	 c = b;
	 b = temp;
	 
	
	 
	 cout << "a = " << a <<endl;
	 cout << "b = "	<< b <<endl;
	 cout << "c = " << c <<endl;
	 
	 return 0;
	
	
	
}
